-- ============================================================
-- FLASHDELIVERY
-- DRIVER CREDENTIAL CORE V1
--
-- Security model:
--
--   - Raw bearer tokens are NEVER persisted.
--   - API stores and compares only SHA-256 hexadecimal hashes.
--   - One ACTIVE credential per driver in V1.
--   - Revoked credentials cannot be reactivated.
--   - Credential owner and token hash are immutable.
--   - RLS is enabled and no public policies are created.
--
-- Authentication transport:
--
--   Authorization: Bearer <raw-driver-token>
--
-- ============================================================


-- ============================================================
-- 1. DRIVER CREDENTIALS
-- ============================================================

create table public.delivery_driver_credentials (
    id uuid primary key default gen_random_uuid(),

    tenant_id uuid not null,
    driver_id uuid not null,

    -- Lowercase SHA-256 hex digest of the raw bearer token.
    -- The raw credential must never be stored here.
    token_hash varchar(64) not null,

    status varchar(20) not null default 'ACTIVE',

    expires_at timestamptz,
    revoked_at timestamptz,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint delivery_driver_credentials_token_hash_check
        check (
            char_length(token_hash) = 64
            and token_hash = lower(token_hash)
            and token_hash ~ '^[0-9a-f]{64}$'
        ),

    constraint delivery_driver_credentials_status_check
        check (
            status in (
                'ACTIVE',
                'REVOKED'
            )
        ),

    constraint delivery_driver_credentials_expiry_check
        check (
            expires_at is null
            or expires_at > created_at
        ),

    constraint delivery_driver_credentials_revoked_at_check
        check (
            revoked_at is null
            or revoked_at >= created_at
        ),

    constraint delivery_driver_credentials_state_check
        check (
            (
                status = 'ACTIVE'
                and revoked_at is null
            )
            or
            (
                status = 'REVOKED'
                and revoked_at is not null
            )
        ),

    constraint fk_delivery_driver_credentials_tenant
        foreign key (
            tenant_id
        )
        references public.tenants(
            id
        )
        on delete cascade,

    constraint fk_delivery_driver_credentials_driver
        foreign key (
            tenant_id,
            driver_id
        )
        references public.delivery_drivers(
            tenant_id,
            id
        )
        on delete cascade,

    constraint uq_delivery_driver_credentials_token_hash
        unique (
            token_hash
        )
);


-- ============================================================
-- 2. ONLY ONE ACTIVE CREDENTIAL PER DRIVER IN V1
--
-- Rotation:
--
--   old credential ACTIVE
--           ↓
--        REVOKED
--           ↓
--   insert new ACTIVE credential
--
-- All of this can later be performed in one transaction.
-- ============================================================

create unique index uq_delivery_driver_credentials_active_driver
    on public.delivery_driver_credentials (
        tenant_id,
        driver_id
    )
    where status = 'ACTIVE';


create index idx_delivery_driver_credentials_driver
    on public.delivery_driver_credentials (
        tenant_id,
        driver_id,
        status,
        created_at desc
    );


-- ============================================================
-- 3. PROTECT CREDENTIAL IDENTITY / REVOCATION
-- ============================================================

create or replace function public.flashdelivery_protect_driver_credential()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin

    -- Credential ownership and secret fingerprint are immutable.
    if new.tenant_id is distinct from old.tenant_id
       or new.driver_id is distinct from old.driver_id
       or new.token_hash is distinct from old.token_hash
    then
        raise exception
            'Driver credential identity is immutable';
    end if;


    -- A revoked credential is permanently revoked.
    if old.status = 'REVOKED'
       and new.status <> 'REVOKED'
    then
        raise exception
            'Revoked driver credential cannot be reactivated';
    end if;


    -- Revocation time is generated by the database when omitted.
    if old.status = 'ACTIVE'
       and new.status = 'REVOKED'
       and new.revoked_at is null
    then
        new.revoked_at = now();
    end if;


    return new;
end;
$function$;


create trigger trg_delivery_driver_credentials_protect
before update
on public.delivery_driver_credentials
for each row
execute function public.flashdelivery_protect_driver_credential();


-- Existing core helper.
create trigger trg_delivery_driver_credentials_updated_at
before update
on public.delivery_driver_credentials
for each row
execute function public.set_updated_at();


-- ============================================================
-- 4. RLS
--
-- No policies are intentionally created.
-- Driver credentials are server-side authentication material.
-- ============================================================

alter table public.delivery_driver_credentials
    enable row level security;


